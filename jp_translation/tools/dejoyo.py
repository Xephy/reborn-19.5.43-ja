def convert(text):
    for a, b in WORDS:
        text = text.replace(a, b)
    for a, b in CHARS.items():
        text = text.replace(a, b)
    return text


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--dry-run', action='store_true')
    a = ap.parse_args()

    joyo = set(open(JOYO, encoding='utf-8').read()) | set('丰')
    changed = files = 0
    left = collections.Counter()
    example = {}
    samples = []

    for path in sorted(glob.glob(os.path.join(SRC, '*.jsonl'))):
        rows = [json.loads(l) for l in open(path, encoding='utf-8') if l.strip()]
        n = 0
        for r in rows:
            ja = r.get('ja')
            if not ja:
                continue
            new = convert(ja)
            if new != ja:
                if len(samples) < 8:
                    samples.append((ja, new))
                r['ja'] = new
                n += 1
            for c in r['ja']:
                if '一' <= c <= '鿿' and c not in joyo:
                    left[c] += 1
                    example.setdefault(c, (os.path.basename(path), r['ja'][:40]))
        if n:
            files += 1
            changed += n
            if not a.dry_run:
                with open(path, 'w', encoding='utf-8', newline='\n') as f:
                    for r in rows:
                        f.write(json.dumps(r, ensure_ascii=False) + '\n')

    print(f'{changed} 行を変換 ({files} ファイル)' + (' — dry run' if a.dry_run else ''))
    for before, after in samples:
        print(f'  前: {before[:50]}\n  後: {after[:50]}')
    if left:
        print(f'\n未対応の常用外漢字: {len(left)} 種 / {sum(left.values())} 箇所')
        for c, n in left.most_common():
            f, ex = example[c]
            print(f'  {c}  {n:3d}  {f:26s} {ex}')
        return 1
    print('\n常用外漢字なし')
    return 0


if __name__ == '__main__':
    sys.exit(main())
